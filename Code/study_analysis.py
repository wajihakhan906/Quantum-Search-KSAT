def _s5_summary(src):
    """{(instance, method): dict(p=[reps], ci, hell, cost)}"""
    out = {}
    for r in rows_of(src, "s5"):
        d = out.setdefault((r["instance"], r["method"]), {"p": [], "ci": [], "hell": [], "cost": [], "ptheory":
                                                           r["p_theory"], "n": r["n"]})
        d["p"].append(r["p"]); d["hell"].append(r["hellinger"]); d["cost"].append(r["est_qpu_s"])
        if r["ci95"]:
            d["ci"].append(r["ci95"])
    return out


def step5(report, S):
    report.append("### Step 5: error mitigation on K-SAT (Oracle A, k = 1, 2 repetitions)\n")
    rows = []
    for s, d in S.items():
        summ = _s5_summary(d)
        for inst in ("5v", "6v"):
            base = np.mean(summ[(inst, "none")]["p"])
            for t in TECH:
                if (inst, t) not in summ:
                    continue
                x = summ[(inst, t)]
                p = np.mean(x["p"])
                lo = min(c[0] for c in x["ci"]) if x["ci"] else None
                hi = max(c[1] for c in x["ci"]) if x["ci"] else None
                rows.append([src_label(s), inst, TECH_LABEL[t], f"{p:.3f}" + (f" [{lo:.3f}, {hi:.3f}]" if lo else ""),
                             f"{p - base:+.3f}", f"{np.mean(x['hell']):.3f}", f"{np.mean(x['cost']):.1f}",
                             f"{np.mean(x['cost']) / np.mean(summ[(inst, 'none')]['cost']):.1f}×"])
    report.append(write_table("tab_II_mitigation", ["Source", "Instance", "Technique", "P(solution) [95% CI]",
                                                    "Gain vs none", "Hellinger", "QPU cost (s)", "Cost ratio"], rows,
                              "Table II: K-SAT success probability per error-mitigation technique "
                              "(ideal: 5v 0.646, 6v 0.371)", "tab:II", "lllrrrrr"))
    fig_mitigation(S)


def fig_mitigation(S):
    fig, axes = plt.subplots(2, 1, figsize=(DOUBLE, 4.6), sharex=True)
    srcs = list(S)
    w = 0.8 / len(srcs)
    for ax, inst, letter in zip(axes, ("5v", "6v"), "ab"):
        ideal = None
        for j, s in enumerate(srcs):
            summ = _s5_summary(S[s])
            st = src_style(s)
            for i, t in enumerate(TECH):
                if (inst, t) not in summ:
                    continue
                x = summ[(inst, t)]
                ideal = x["ptheory"]
                p = float(np.mean(x["p"]))
                xpos = i + (j - (len(srcs) - 1) / 2) * w
                ax.bar(xpos, p, w * 0.9, color=st["color"], alpha=1 if is_hw(s) else 0.85, hatch=st["hatch"],
                       edgecolor="white", linewidth=0.4)
                if x["ci"]:
                    lo, hi = min(c[0] for c in x["ci"]), max(c[1] for c in x["ci"])
                    ax.plot([xpos, xpos], [lo, hi], color=INK, lw=0.7)
                ax.text(xpos, p + 0.015, f"{p:.2f}", ha="center", va="bottom", fontsize=5.4, color=INK2, rotation=90)
        n = 5 if inst == "5v" else 6
        ax.axhline(ideal, color=INK, lw=1, ls="-", zorder=0.5)
        ax.text(len(TECH) - 0.45, ideal, " ideal", va="center", fontsize=6.5, color=INK)
        ax.axhline(3 / 2**n, color=MUTED, lw=1, ls=":", zorder=0.5)
        ax.text(len(TECH) - 0.45, 3 / 2**n, " random", va="center", fontsize=6.5, color=MUTED)
        ax.set(ylabel="P(solution)", ylim=(0, max(ideal * 1.25, 0.5)), xlim=(-0.6, len(TECH) - 0.4))
        cnf = {"5v": "5 variables, 6 clauses", "6v": "6 variables, 7 clauses"}[inst]
        ax.set_title(f"{inst[0]}-variable K-SAT ({cnf}), Oracle A, $k=1$", loc="left")
        panel(ax, letter, -0.07)
    axes[-1].set_xticks(range(len(TECH)))
    axes[-1].set_xticklabels([TECH_LABEL[t] for t in TECH])
    handles = [Patch(facecolor=src_style(s)["color"], hatch=src_style(s)["hatch"], edgecolor="white",
                     alpha=1 if is_hw(s) else 0.85, label=src_label(s)) for s in srcs]
    handles.append(Line2D([], [], color=INK, lw=0.7, label="95% bootstrap CI"))
    fig.legend(handles=handles, loc="upper center", ncol=len(handles), bbox_to_anchor=(0.5, 1.01))
    fig.tight_layout(rect=(0, 0, 1, 0.96), h_pad=1.2)
    save_fig(fig, "fig03_mitigation")


