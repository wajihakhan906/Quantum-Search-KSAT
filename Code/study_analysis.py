def step12(report, S):
    report.append("### Step 12: statistics and cost–benefit\n")
    report.append("95% confidence intervals are percentile bootstraps (1000 resamples of the shots for unmitigated "
                  "runs, 200 for mitigated runs, which recompute the whole mitigation from resampled counts). "
                  "Hellinger fidelity compares each output distribution with the exact one.\n")
    rows, pts = [], []
    for s, d in S.items():
        summ = _s5_summary(d)
        for t in TECH:
            gains, dh, costs, ratios = [], [], [], []
            for inst in ("5v", "6v"):
                if (inst, t) not in summ:
                    continue
                x, b = summ[(inst, t)], summ[(inst, "none")]
                gains.append(np.mean(x["p"]) - np.mean(b["p"]))
                dh.append(np.mean(x["hell"]) - np.mean(b["hell"]))
                costs.append(np.mean(x["cost"]))
                ratios.append(np.mean(x["cost"]) / np.mean(b["cost"]))
            if not gains:
                continue
            g, c = float(np.mean(gains)), float(np.mean(costs))
            extra = c - np.mean([np.mean(summ[(i, "none")]["cost"]) for i in ("5v", "6v")])
            pts.append((s, t, float(np.mean(ratios)), g))
            rows.append([src_label(s), TECH_LABEL[t], f"{g:+.3f}", f"{np.mean(dh):+.3f}", f"{c:.1f}",
                         f"{np.mean(ratios):.1f}×", "–" if t == "none" else f"{g / extra:+.4f}" if extra > 1e-9 else "–"])
    report.append(write_table("tab_step12_cost_benefit", ["Source", "Technique", "ΔP(solution)", "ΔHellinger",
                                                          "QPU cost per run (s)", "Cost ratio", "ΔP per extra second"],
                              rows, "Cost–benefit of each mitigation technique (average of both instances)",
                              "tab:cost", "llrrrrr"))
    fig, ax = plt.subplots(figsize=(SINGLE + 0.6, 2.8))
    ax.axhline(0, color=INK2, lw=0.8)
    markers = {"kingston": "o", "marrakesh": "s"}
    for s, t, ratio, g in pts:
        hw = is_hw(s)
        ax.plot(ratio, g, markers[dev_of(s)], ms=6.5, color=TECH_COLOR[t], mfc=TECH_COLOR[t] if hw else "white",
                mew=1.3, mec=TECH_COLOR[t])
        ax.annotate(TECH_LABEL[t], (ratio, g), xytext=(5, 2), textcoords="offset points", fontsize=6.2,
                    color=INK2)
    ax.set_xscale("log")
    ax.set(xlabel="QPU cost relative to no mitigation", ylabel=r"Gain $\Delta P$(solution)")
    ax.grid(True, axis="both")
    handles = [Line2D([], [], marker=markers[dv], ls="", color=INK2, mfc="white", label=f"{dv.capitalize()}")
               for dv in markers if any(dev_of(s) == dv for s in S)]
    handles += [Line2D([], [], marker="o", ls="", color=INK2, mfc=INK2, label="filled = QPU"),
                Line2D([], [], marker="o", ls="", color=INK2, mfc="white", label="hollow = model")]
    ax.legend(handles=handles, loc="best", fontsize=6.2)
    fig.tight_layout()
    save_fig(fig, "fig09_cost_benefit")
    return pts


def recommendations(report, S, pts, fits):
    report.append("### Practical recommendations\n")
    lines = []
    for s in S:
        cand = [(g, r, t) for (src, t, r, g) in pts if src == s and t != "none"]
        if not cand:
            continue
        best = max(cand)
        cheap = [c for c in cand if c[1] <= 1.2]
        best_cheap = max(cheap) if cheap else None
        per_sec = max(cand, key=lambda c: c[0] / max(c[1] - 1, 0.05))
        lines.append(f"- **{src_label(s)}**: largest gain from **{TECH_LABEL[best[2]]}** (ΔP = {best[0]:+.3f} at "
                     f"{best[1]:.1f}× QPU cost); best value per QPU second **{TECH_LABEL[per_sec[2]]}** "
                     f"({per_sec[0]:+.3f})"
                     + (f"; best at ≤1.2× cost **{TECH_LABEL[best_cheap[2]]}** ({best_cheap[0]:+.3f})."
                        if best_cheap else "."))
    for s, F in fits.items():
        lines.append(f"- {src_label(s)}: effective CZ fidelity {F:.4f}. A circuit keeps only 1% of its ideal "
                     f"signal after ≈{math.log(0.01) / math.log(F):.0f} CZ gates, so compilation (fewer CZ) matters "
                     "more than mitigation once circuits exceed a few hundred CZ gates.")
    report.append("\n".join(lines) + "\n")


