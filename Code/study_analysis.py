def fit_F(rows):
    """Least-squares F in P = P_ideal F^g + (1 - F^g)/2^n over unmitigated Grover runs."""
    data = [(r["p"], r["p_theory"], r["cz"], r["n"]) for r in rows]

    def loss(F):
        return sum((p - (pi * F**g + (1 - F**g) / 2**n)) ** 2 for p, pi, g, n in data)

    res = minimize_scalar(loss, bounds=(0.9, 0.99999), method="bounded")
    rng = np.random.default_rng(0)
    boot = []
    for _ in range(300):
        smp = [data[i] for i in rng.integers(0, len(data), len(data))]
        boot.append(minimize_scalar(lambda F: sum((p - (pi * F**g + (1 - F**g) / 2**n)) ** 2
                                                  for p, pi, g, n in smp), bounds=(0.9, 0.99999),
                                    method="bounded").x)
    return float(res.x), [float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5))]


def step10(report, S, d1):
    report.append("### Step 10: noise-scaling model\n")
    rows, fits = [], {}
    grover_cz = {}
    if d1:
        for v in orc.VARIANTS:
            rr = [r for r in d1["rows"] if r["circuit"].startswith("Grover") and r["variant"] == v]
            grover_cz[v] = ([r["n_vars"] for r in rr], [r["cz_kingston"] for r in rr])
    for s, d in S.items():
        rr = rows_of(d, "s7") + rows_of(d, "s8")
        F, ci = fit_F(rr)
        fits[s] = F
        e_cal = d["calibration"]["used"]["cz_error_median"] or d["calibration"]["device"]["cz_error_median"]
        g_rand = math.log(0.01) / math.log(F)
        n_rand = {}
        for v, (ns, cz) in grover_cz.items():  # first n where one iteration keeps <1% of the signal
            slope, icpt = np.polyfit(ns[-4:], np.log(cz[-4:]), 1)
            n_rand[v] = next((n for n in range(2, 60) if (cz[ns.index(n)] if n in ns else math.exp(icpt + slope * n))
                              >= g_rand), None)
        rows.append([src_label(s), f"{F:.5f} [{ci[0]:.5f}, {ci[1]:.5f}]", f"{1 - F:.2e}", f"{e_cal:.2e}",
                     f"{(1 - F) / e_cal:.1f}×", f"{g_rand:.0f}", n_rand.get("noancilla"), n_rand.get("vchain_rtof")])
